"""Evaluation harness: python run_eval.py [--split dev|heldout|all]. Prints a table, writes results/eval_report.md."""
from __future__ import annotations

import argparse
import json
import logging
from pathlib import Path

from assistant.agent import TyreAssistant

ROOT = Path(__file__).resolve().parent
SPLITS = {"dev": ROOT / "eval" / "dev_questions.jsonl", "heldout": ROOT / "eval" / "heldout_handwritten.jsonl"}
REFUSAL_ROUTES = {"safety", "out_of_scope"}


def load(path: Path) -> list[dict]:
    return [json.loads(l) for l in path.read_text(encoding="utf-8").splitlines() if l.strip()]


def _rate(xs: list[bool]) -> float | None:
    return round(sum(xs) / len(xs), 3) if xs else None


def evaluate(items: list[dict], bot: TyreAssistant) -> tuple[dict, list[dict]]:
    rows = []
    for it in items:
        r = bot.ask(it["question"])
        top3 = [d.doc_id for d, _ in bot.retriever.search(it["question"], k=3)]
        exp_docs = it.get("expected_doc_ids") or []
        ans = r["answer"].lower()
        exp_tool = it.get("expected_tool")
        tool_ok = None
        if exp_tool is not None:
            tr = r.get("tool_result") or {}
            tool_ok = r["route"] == "tool" and all(tr.get(k) == v for k, v in exp_tool.items())
        rows.append({
            "id": it["id"], "question": it["question"], "expected_route": it["expected_route"],
            "route": r["route"], "route_ok": r["route"] == it["expected_route"],
            # retrieval scored only for questions that should be answered from the KB
            "hit3": any(d in top3 for d in exp_docs) if exp_docs and it["expected_route"] == "rag" else None,
            "facts_ok": all(f.lower() in ans for f in it.get("key_facts", [])),
            "tool_ok": tool_ok, "top3": top3, "answer": r["answer"], "latency_ms": r["latency_ms"],
        })
    should_refuse = [x for x in rows if x["expected_route"] in REFUSAL_ROUTES]
    should_answer = [x for x in rows if x["expected_route"] not in REFUSAL_ROUTES]
    metrics = {
        "n": len(rows),
        "route_accuracy": _rate([x["route_ok"] for x in rows]),
        "retrieval_hit@3": _rate([x["hit3"] for x in rows if x["hit3"] is not None]),
        "key_fact_accuracy": _rate([x["facts_ok"] for x in rows]),
        "unsafe_refusal_rate": _rate([x["route"] in REFUSAL_ROUTES for x in should_refuse]),
        "false_refusal_rate": _rate([x["route"] in REFUSAL_ROUTES for x in should_answer]),
        "tool_correctness": _rate([x["tool_ok"] for x in rows if x["tool_ok"] is not None]),
        "mean_latency_ms": round(sum(x["latency_ms"] for x in rows) / max(len(rows), 1), 2),
    }
    return metrics, rows


def failures(rows: list[dict]) -> list[dict]:
    return [x for x in rows if not x["route_ok"] or not x["facts_ok"] or x["hit3"] is False or x["tool_ok"] is False]


def render(results: dict[str, tuple[dict, list[dict]]]) -> str:
    names = list(results)
    keys = list(next(iter(results.values()))[0])
    out = ["| metric | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
    for k in keys:
        out.append(f"| {k} | " + " | ".join(str(results[n][0][k]) for n in names) + " |")
    return "\n".join(out)


def main(argv=None) -> dict:
    ap = argparse.ArgumentParser()
    ap.add_argument("--split", choices=["dev", "heldout", "all"], default="all")
    ap.add_argument("--report", default=str(ROOT / "results" / "eval_report.md"))
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.WARNING)
    bot = TyreAssistant()
    names = ["dev", "heldout"] if args.split == "all" else [args.split]
    results = {n: evaluate(load(SPLITS[n]), bot) for n in names if SPLITS[n].exists()}
    table = render(results)
    print(table)
    lines = ["# Evaluation report", "", "Offline mode (TF-IDF retrieval + ScriptedLLM). Generated by `python run_eval.py`.",
             "", table, ""]
    for n, (_, rows) in results.items():
        fails = failures(rows)
        lines += [f"## {n} failures ({len(fails)})", ""]
        for x in fails:
            lines.append(f"- **{x['id']}** `{x['question']}` -> route `{x['route']}` (expected `{x['expected_route']}`), "
                         f"top3 {x['top3']}, facts_ok={x['facts_ok']}, tool_ok={x['tool_ok']}")
        lines.append("")
    Path(args.report).parent.mkdir(parents=True, exist_ok=True)
    Path(args.report).write_text("\n".join(lines), encoding="utf-8")
    for n, (_, rows) in results.items():
        for x in failures(rows):
            print(f"FAIL [{n}] {x['id']}: {x['question']} -> {x['route']} | {x['answer'][:140]!r}")
    return {n: m for n, (m, _) in results.items()}


if __name__ == "__main__":
    main()
